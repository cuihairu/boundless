//! BW-01-02-04 compressed stream.
//!
//! Port of the reference `lib/network/zip_stream.hpp` `ZipOStream` /
//! `ZipIStream` pair. The reference classes are generic over a `BinaryStream`
//! and depend only on cstdmf and zlib (they live in `lib/network` because
//! compression is historically a bundle concern, but the wrapper itself is not
//! network-coupled), so they belong here beside the stream codecs.
//!
//! Wire form written by `ZipOStream` (its destructor is the flush):
//! * `writeStringLength( srcLen )` — packed int, the uncompressed length;
//! * `writeStringLength( dstLen )` — packed int, the compressed length;
//! * the zlib-compressed blob (`compress2`, level defaults to 1/Z_BEST_SPEED).
//!
//! `ZipIStream::init` reads both lengths, rejects a declared compressed length
//! that does not fit the remaining bytes, rejects a declared uncompressed
//! length beyond DEFLATE's worst-case expansion (`origLen > compressLen *
//! 1032`, RFC 1951 — the CR-P2-21 guard against a hostile allocation), then
//! `uncompress`s into a buffer it owns and becomes a read stream over the
//! decompressed payload.

use crate::stream::{BinaryStream, StreamError, MAX_PACKED_INT};

/// The reference `ZipOStream` default compression level: `Z_BEST_SPEED`.
pub const DEFAULT_COMPRESSION_LEVEL: u32 = 1;

/// DEFLATE's worst-case expansion ratio (RFC 1951), the reference's bound on a
/// declared uncompressed length. The reference rejects any declaration beyond
/// `compressLen * 1032` before allocating (CR-P2-21).
pub const WORST_CASE_EXPANSION: u64 = 1032;

/// A writer that buffers uncompressed bytes and, on `finish`, appends the
/// reference compressed form to the destination stream. Mirrors the reference
/// `ZipOStream` (whose destructor is the flush).
pub struct CompressedWriter<'a> {
    dst: &'a mut BinaryStream,
    buf: Vec<u8>,
    level: u32,
}

impl<'a> CompressedWriter<'a> {
    /// Create a writer over `dst` at the reference default level.
    pub fn new(dst: &'a mut BinaryStream) -> Self {
        Self::with_level(dst, DEFAULT_COMPRESSION_LEVEL)
    }

    /// Create a writer over `dst` at an explicit zlib level (0-9).
    pub fn with_level(dst: &'a mut BinaryStream, level: u32) -> Self {
        Self {
            dst,
            buf: Vec::new(),
            level,
        }
    }

    /// Buffer uncompressed bytes; they are compressed together at `finish`.
    pub fn write(&mut self, bytes: &[u8]) {
        self.buf.extend_from_slice(bytes);
    }

    /// Compress the buffered bytes and append the reference form to `dst`.
    pub fn finish(self) -> Result<(), StreamError> {
        if self.buf.len() > MAX_PACKED_INT as usize {
            return Err(StreamError::PackedIntTooLarge);
        }
        let mut encoder =
            flate2::write::ZlibEncoder::new(Vec::new(), flate2::Compression::new(self.level));
        std::io::Write::write_all(&mut encoder, &self.buf).map_err(|_| StreamError::CorruptData)?;
        let compressed = encoder.finish().map_err(|_| StreamError::CorruptData)?;
        if compressed.len() > MAX_PACKED_INT as usize {
            return Err(StreamError::PackedIntTooLarge);
        }
        self.dst.write_packed_int(self.buf.len() as u32)?;
        self.dst.write_packed_int(compressed.len() as u32)?;
        self.dst.write_bytes(&compressed);
        Ok(())
    }
}

impl BinaryStream {
    /// Read a reference compressed form and return a stream over the
    /// decompressed payload. Mirrors `ZipIStream::init`: reads the packed
    /// uncompressed and compressed lengths, applies the reference guards, and
    /// `uncompress`es the blob.
    pub fn read_compressed(&mut self) -> Result<BinaryStream, StreamError> {
        let orig_len = self.read_packed_int()? as usize;
        let compress_len = self.read_packed_int()? as usize;

        // `ZipIStream::init`: the declared compressed length must fit the
        // remaining bytes, and the declared uncompressed length must be within
        // DEFLATE's worst-case expansion of it (CR-P2-21).
        if compress_len > self.remaining() {
            return Err(StreamError::Truncated);
        }
        if orig_len as u64 > compress_len as u64 * WORST_CASE_EXPANSION {
            return Err(StreamError::CorruptData);
        }

        let blob = self.read_blob_raw(compress_len)?;
        let mut out = Vec::with_capacity(orig_len);
        let mut decoder = flate2::read::ZlibDecoder::new(&blob[..]);
        std::io::Read::read_to_end(&mut decoder, &mut out).map_err(|_| StreamError::CorruptData)?;

        let mut payload = BinaryStream::new();
        payload.write_bytes(&out);
        payload.rewind();
        Ok(payload)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::stream::{BinaryStream, StreamError};

    /// The reference's own `ZipOStream` output for `REFERENCE_PAYLOAD`
    /// (generated by a fixture compiled against the reference cstdmf and
    /// `libnetwork.a`): packed srcLen (110), packed dstLen (33), then the
    /// 33-byte zlib blob.
    const REFERENCE_FIXTURE: &[u8] = &[
        0x6E, 0x21, // srcLen=110, dstLen=33
        0x78, 0x01, 0xCB, 0x4D, 0xCD, 0x2B, 0xC9, 0x2C, 0xA9, 0x4C, 0x49, 0x4D, 0xB3, 0x4A, 0x4A,
        0x2C, 0x4E, 0xD5, 0x77, 0x2C, 0x4B, 0x2C, 0x49, 0x2C, 0x52, 0xA0, 0x91, 0x28, 0x00, 0x1E,
        0xBA, 0x29, 0xD9,
    ];

    /// The string the reference compressed. It is length-prefixed inside the
    /// uncompressed stream (`zip << BW::string(payload)`), so the decompressed
    /// buffer is 1 + 109 bytes.
    const REFERENCE_PAYLOAD: &str = "entitydef:base/Avatar entitydef:base/Avatar entitydef:base/Avatar entitydef:base/Avatar entitydef:base/Avatar";

    #[test]
    fn reference_zip_fixture_decodes() {
        let mut src = BinaryStream::new();
        src.write_bytes(REFERENCE_FIXTURE);
        src.rewind();

        let mut payload = src.read_compressed().expect("reference fixture decodes");
        // The uncompressed stream is the string form `zip << BW::string(...)`:
        // a packed length prefix plus the raw bytes, so `read_string` recovers
        // it directly.
        assert_eq!(payload.remaining(), 1 + REFERENCE_PAYLOAD.len());
        assert_eq!(payload.read_string(), Ok(REFERENCE_PAYLOAD.to_string()));
        assert!(payload.at_end());
    }

    #[test]
    fn zip_roundtrip_matches_reference() {
        // Mirror `zip << BW::string(payload)`: a packed length prefix plus the
        // raw bytes, compressed through the writer and read back.
        let mut dst = BinaryStream::new();
        {
            let mut writer = CompressedWriter::new(&mut dst);
            let mut prefix = BinaryStream::new();
            prefix
                .write_packed_int(REFERENCE_PAYLOAD.len() as u32)
                .unwrap();
            writer.write(prefix.as_bytes());
            writer.write(REFERENCE_PAYLOAD.as_bytes());
            writer.finish().unwrap();
        }

        // Wire form: packed srcLen byte, packed dstLen byte, zlib CMF byte.
        assert_eq!(dst.as_bytes()[0], 0x6E); // packed(110)
        assert_eq!(dst.as_bytes()[2], 0x78); // zlib header (CMF)

        let mut payload = dst.read_compressed().expect("round-trips");
        assert_eq!(payload.read_string(), Ok(REFERENCE_PAYLOAD.to_string()));
        assert!(payload.at_end());
    }

    #[test]
    fn compressed_guards_match_the_reference() {
        // The reference rejects a declared uncompressed length beyond DEFLATE's
        // worst-case expansion of the compressed length (CR-P2-21).
        let mut src = BinaryStream::new();
        src.write_packed_int(2_000).unwrap();
        src.write_packed_int(1).unwrap();
        src.write_bytes(&[0x00]);
        src.rewind();
        assert_eq!(src.read_compressed().unwrap_err(), StreamError::CorruptData);

        // A declared compressed length that does not fit the remaining bytes.
        let mut src = BinaryStream::new();
        src.write_packed_int(10).unwrap();
        src.write_packed_int(100).unwrap();
        src.write_bytes(&[0x00]);
        src.rewind();
        assert_eq!(src.read_compressed().unwrap_err(), StreamError::Truncated);

        // A blob that does not decode as zlib.
        let mut src = BinaryStream::new();
        src.write_packed_int(10).unwrap();
        src.write_packed_int(3).unwrap();
        src.write_bytes(&[0x01, 0x02, 0x03]);
        src.rewind();
        assert_eq!(src.read_compressed().unwrap_err(), StreamError::CorruptData);
    }
}
