//! Callable watchers (BW-12-01-03): the `CallableWatcher` family —
//! `ExposeHint`, the declared argument list, the `Callable function` read
//! result, and the call that returns a `(stdio output, value)` pair.
//!
//! Ported from `programming/bigworld/lib/cstdmf/watcher.{hpp,cpp}` and
//! `watcher.hpp`'s `NoArgCallableWatcher`/`SimpleCallableWatcher`, pinned to
//! the original suite `lib/cstdmf/unit_test/test_watcher_gaps.cpp` (the
//! callable is constructed, not tree-registered, there).

use super::path_tree::{Mode, WatcherDataType, WatcherValue};

/// `CallableWatcher::ExposeHint` (watcher.hpp:2867-2874): how the callable
/// is exposed to callers.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum ExposeHint {
    /// `WITH_ENTITY`
    WithEntity,
    /// `ALL`
    All,
    /// `WITH_SPACE`
    WithSpace,
    /// `LEAST_LOADED`
    LeastLoaded,
    /// `LOCAL_ONLY` — the default.
    #[default]
    LocalOnly,
}

/// `CallableWatcher::ArgDescription` (watcher.hpp:2876-2888): one declared
/// argument — its protocol type and its description.
#[derive(Debug, Clone, PartialEq)]
pub struct ArgDescription {
    data_type: WatcherDataType,
    description: String,
}

impl ArgDescription {
    /// A declared argument.
    pub fn new(data_type: WatcherDataType, description: &str) -> Self {
        Self {
            data_type,
            description: description.to_string(),
        }
    }

    /// The argument's protocol type.
    pub const fn data_type(&self) -> WatcherDataType {
        self.data_type
    }

    /// The argument's description.
    pub fn description(&self) -> &str {
        &self.description
    }
}

/// The pair a callable returns: the `stdio output` it generated and its
/// return value — exactly what `CallableWatcher::startResultStream`
/// streams as a two-element `WATCHER_TYPE_TUPLE` (watcher.hpp:2884-2916).
#[derive(Debug, Clone, PartialEq)]
pub struct CallResult {
    /// The stdio output generated by the call.
    pub output: String,
    /// The call's return value.
    pub value: WatcherValue,
}

/// The callable function: `onCall` receives the typed arguments and fills
/// in the `(output, value)` pair (watcher.hpp:2957-2960).
pub type Callable = Box<dyn Fn(&[WatcherValue]) -> CallResult>;

/// `CallableWatcher` (watcher.hpp:2855-2914): a watcher whose read result
/// is `Callable function` with `WT_CALLABLE`, whose `setFromString` is
/// refused (v1 calling is not supported, watcher.cpp:663-674), and which
/// is invoked through its function with the declared arguments. The
/// function is a boxed closure, so the watcher is not itself `Debug`.
pub struct CallableWatcher {
    expose_hint: ExposeHint,
    args: Vec<ArgDescription>,
    comment: String,
    function: Callable,
}

impl CallableWatcher {
    /// A callable watcher with the default `LOCAL_ONLY` hint, no comment
    /// and no arguments, bound to `function`.
    pub fn new(function: Callable) -> Self {
        Self {
            expose_hint: ExposeHint::LocalOnly,
            args: Vec::new(),
            comment: String::new(),
            function,
        }
    }

    /// A callable watcher with a comment, bound to `function`.
    pub fn with_comment(comment: &str, function: Callable) -> Self {
        Self {
            expose_hint: ExposeHint::LocalOnly,
            args: Vec::new(),
            comment: comment.to_string(),
            function,
        }
    }

    /// `CallableWatcher::addArg` (watcher.cpp:635-639): append a declared
    /// argument with its type and description.
    pub fn add_arg(&mut self, data_type: WatcherDataType, description: &str) {
        self.args.push(ArgDescription::new(data_type, description));
    }

    /// The declared arguments, in order.
    pub fn args(&self) -> &[ArgDescription] {
        &self.args
    }

    /// `CallableWatcher::exposedHint` (watcher.hpp:2876-2883).
    pub const fn expose_hint(&self) -> ExposeHint {
        self.expose_hint
    }

    /// `CallableWatcher::exposeHint` (watcher.hpp:2879-2883).
    pub fn set_expose_hint(&mut self, hint: ExposeHint) {
        self.expose_hint = hint;
    }

    /// The callable's comment (`Watcher::getComment`).
    pub fn comment(&self) -> &str {
        &self.comment
    }

    /// `CallableWatcher::setComment` (watcher.hpp:913-915).
    pub fn set_comment(&mut self, comment: &str) {
        self.comment = comment.to_string();
    }

    /// `CallableWatcher::getAsString` (watcher.cpp:644-660): an empty path
    /// reports `Callable function` with `WT_CALLABLE`; any other path
    /// fails.
    pub fn get_string(&self, path: &str) -> Option<(String, Mode)> {
        if path.is_empty() {
            Some(("Callable function".to_string(), Mode::Callable))
        } else {
            None
        }
    }

    /// `CallableWatcher::setFromString` (watcher.cpp:663-674): the v1 call
    /// protocol is unsupported, so a string write is always refused.
    pub fn set_string(&mut self, path: &str, value_str: &str) -> bool {
        let _ = (path, value_str);
        false
    }

    /// `CallableWatcher::isArgsPath` (watcher.cpp:732-741): whether `path`
    /// is the `__args__` path.
    pub fn is_args_path(path: &str) -> bool {
        path == "__args__"
    }

    /// `CallableWatcher::isExposePath` (watcher.cpp:744-753): whether `path`
    /// is the `__expose__` path.
    pub fn is_expose_path(path: &str) -> bool {
        path == "__expose__"
    }

    /// Invoke the callable: the function receives the typed arguments and
    /// returns the `(output, value)` pair (the `onCall` hook of
    /// `NoArgFuncCallableWatcher`/`SimpleCallableWatcher`).
    pub fn call(&self, args: &[WatcherValue]) -> CallResult {
        (self.function)(args)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A callable mirroring `GapSimpleCallable` (test_watcher_gaps.cpp:182-194):
    /// empty stdio output, a `gap-result` return value, ignoring arguments.
    fn gap_callable() -> CallableWatcher {
        CallableWatcher::with_comment(
            "gap",
            Box::new(|_args: &[WatcherValue]| CallResult {
                output: String::new(),
                value: WatcherValue::String("gap-result".into()),
            }),
        )
    }

    /// The reference constructs a callable with the default LOCAL_ONLY
    /// hint and a comment (test_watcher_gaps.cpp:185).
    #[test]
    fn a_callable_carries_its_comment_and_default_hint() {
        let callable = gap_callable();
        assert_eq!(callable.comment(), "gap");
        assert_eq!(callable.expose_hint(), ExposeHint::LocalOnly);
        assert!(callable.args().is_empty());

        // setComment (watcher.hpp:913-915) replaces the comment.
        let mut callable = callable;
        callable.set_comment("new comment");
        assert_eq!(callable.comment(), "new comment");
    }

    /// The reference callable returns `gap-result` with empty stdio output
    /// (test_watcher_gaps.cpp:189-192).
    #[test]
    fn the_reference_callable_returns_gap_result() {
        let result = gap_callable().call(&[]);
        assert_eq!(result.output, "");
        assert_eq!(result.value, WatcherValue::String("gap-result".into()));
    }

    /// `addArg` appends typed arguments in order, and the hint is settable
    /// (watcher.hpp:2876-2883, 2933-2950).
    #[test]
    fn arguments_carry_their_type_and_description() {
        let mut callable = gap_callable();
        callable.add_arg(WatcherDataType::Int, "count");
        callable.add_arg(WatcherDataType::String, "name");

        let args = callable.args();
        assert_eq!(args.len(), 2);
        assert_eq!(args[0].data_type(), WatcherDataType::Int);
        assert_eq!(args[0].description(), "count");
        assert_eq!(args[1].data_type(), WatcherDataType::String);
        assert_eq!(args[1].description(), "name");

        callable.set_expose_hint(ExposeHint::All);
        assert_eq!(callable.expose_hint(), ExposeHint::All);
    }

    /// The acceptance: a call carries its arguments and returns the value
    /// the function produces — the `(output, value)` pair the reference
    /// streams as a two-element tuple (watcher.hpp:2884-2916).
    #[test]
    fn a_call_takes_its_arguments_and_returns_its_value() {
        let mut callable = CallableWatcher::new(Box::new(|args: &[WatcherValue]| match args {
            [WatcherValue::Int(count), WatcherValue::String(name)] => CallResult {
                output: format!("spawned {count} of {name}"),
                value: WatcherValue::Uint(42),
            },
            _ => CallResult {
                output: String::new(),
                value: WatcherValue::Bool(false),
            },
        }));
        callable.add_arg(WatcherDataType::Int, "count");
        callable.add_arg(WatcherDataType::String, "name");

        let result = callable.call(&[WatcherValue::Int(3), WatcherValue::String("bot".into())]);
        assert_eq!(result.output, "spawned 3 of bot");
        assert_eq!(result.value, WatcherValue::Uint(42));

        // A mismatched argument list falls to the function's own failure
        // arm, as `onCall` would.
        let bad = callable.call(&[WatcherValue::Bool(true)]);
        assert_eq!(bad.output, "");
        assert_eq!(bad.value, WatcherValue::Bool(false));
    }

    /// `CallableWatcher::getAsString` (watcher.cpp:644-660): the empty path
    /// reports `Callable function` with WT_CALLABLE; any other path fails.
    #[test]
    fn get_string_reports_callable_function() {
        let callable = gap_callable();
        assert_eq!(
            callable.get_string(""),
            Some(("Callable function".to_string(), Mode::Callable))
        );
        assert_eq!(callable.get_string("args"), None);
        assert_eq!(callable.get_string("__args__"), None);
    }

    /// `CallableWatcher::setFromString` (watcher.cpp:663-674): v1 calling
    /// is unsupported, so a string write is always refused.
    #[test]
    fn set_string_is_always_refused() {
        let mut callable = gap_callable();
        assert!(!callable.set_string("", "anything"));
        assert!(!callable.set_string("__args__", "1"));
    }

    /// `CallableWatcher::isArgsPath`/`isExposePath` (watcher.cpp:732-753)
    /// match only their exact path.
    #[test]
    fn the_special_paths_match_only_themselves() {
        assert!(CallableWatcher::is_args_path("__args__"));
        assert!(CallableWatcher::is_expose_path("__expose__"));
        assert!(!CallableWatcher::is_args_path("__expose__"));
        assert!(!CallableWatcher::is_args_path("args"));
        assert!(!CallableWatcher::is_expose_path("__args__"));
        assert!(!CallableWatcher::is_expose_path(""));
        assert!(!CallableWatcher::is_args_path(""));
    }
}
