//! `TaskStore` port (`tools/jit_compiler/task_store.{hpp,cpp}` plus
//! `task_info.{hpp,cpp}`): the task bookkeeping the JIT compiler drives and
//! the JIT tool's UI reads.
//!
//! Reference quirks preserved:
//! - tasks live in four lists — `requestedTasks_`, `currentTasks_`,
//!   `completedTasks_` and `allTasks_` — keyed by task identity; a task moves
//!   requested → current → completed, and `resetTask` evicts it from the
//!   completed list while clearing its info record;
//! - `addRequestedTask` is idempotent (a task already in the requested list
//!   is left alone);
//! - `setTaskComplete` removes the task from the current *and* requested
//!   lists before inserting it into the completed list;
//! - `handleTaskMessage` appends the message to the task's log and raises
//!   its error/warning flags per the message priority, reporting whether the
//!   task was known (the reference returns whether the store handled it);
//! - the per-task info holds the source, the pipeline state, the log, the
//!   generated outputs and the sub-task list.
//!
//! Port deviations (both structural, behaviour preserved):
//! - the reference keys its maps by `ConversionTask*`; here tasks are
//!   identified by their [`TaskHandle`] address (the same convention the
//!   batch driver's stats use);
//! - the `Signal`/`Connection` UI plumbing and the `SimpleMutex` guards are
//!   not modelled — the single-threaded port exposes the four lists as the
//!   queryable face and the scanning callbacks as plain boxed closures.

use std::cell::RefCell;
use std::collections::{HashMap, HashSet};
use std::rc::Rc;

use crate::conversion_task::ConversionTask;

/// The pipeline state a task info records (`TaskInfoState`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum TaskInfoState {
    /// `NONE`.
    #[default]
    None,
    /// `CHECKING`.
    Checking,
    /// `GENERATING_DEPENDENCIES`.
    GeneratingDependencies,
    /// `CONVERTING`.
    Converting,
}

/// A task identity: the [`TaskHandle`] address (the reference's
/// `ConversionTask*` key).
pub type TaskKey = usize;

/// The identity of a `ConversionTask` handle (see [`task_key`]).
pub fn task_key(task: &ConversionTask) -> TaskKey {
    task as *const ConversionTask as usize
}

/// `TaskInfo`: the per-task record the store keeps (see the module docs).
#[derive(Debug, Clone, Default)]
pub struct TaskInfo {
    /// `source_`: the task's source file.
    pub source: String,
    /// `state_`: the pipeline state last recorded for the task.
    pub state: TaskInfoState,
    /// The log messages appended to the task (`log_`).
    pub log: Vec<String>,
    /// The outputs generated by the task (`outputs_`).
    pub outputs: Vec<String>,
    /// The sub-task sources (`subTasks_`, resolved to sources).
    pub sub_tasks: Vec<String>,
    /// `error_` / `warning_`: the flags `handleTaskMessage` raises.
    pub errors: bool,
    pub warnings: bool,
}

impl TaskInfo {
    /// `TaskInfo( task )`.
    fn new(task: &ConversionTask) -> Self {
        Self {
            source: task.source.clone(),
            ..Self::default()
        }
    }
}

/// `TaskStore`: the JIT compiler's task bookkeeping (see the module docs).
#[derive(Default)]
pub struct TaskStore {
    /// `requestedTasks_`.
    requested: RefCell<HashSet<TaskKey>>,
    /// `currentTasks_`.
    current: RefCell<HashSet<TaskKey>>,
    /// `completedTasks_`.
    completed: RefCell<HashSet<TaskKey>>,
    /// `allTasks_`: the info records.
    all: RefCell<HashMap<TaskKey, TaskInfo>>,
    /// `failedCount_` / `warningCount_` (kept by `updateErrorWarningCounts`).
    failed_count: std::cell::Cell<i32>,
    warning_count: std::cell::Cell<i32>,
    /// `scanningStartedCallback_` / `scanningStoppedCallback_`.
    scanning_started_callback: RefCell<Option<Box<dyn Fn()>>>,
    scanning_stopped_callback: RefCell<Option<Box<dyn Fn()>>>,
}

impl TaskStore {
    /// `TaskStore()`.
    pub fn new() -> Self {
        Self::default()
    }

    /// `setStatusCallbacks`: install the scanning callbacks (the only two
    /// the reference store keeps as plain callbacks).
    pub fn set_status_callbacks(
        &self,
        scanning_started: Option<Box<dyn Fn()>>,
        scanning_stopped: Option<Box<dyn Fn()>>,
    ) {
        *self.scanning_started_callback.borrow_mut() = scanning_started;
        *self.scanning_stopped_callback.borrow_mut() = scanning_stopped;
    }

    /// `scanningStarted`.
    pub fn scanning_started(&self) {
        if let Some(callback) = self.scanning_started_callback.borrow().as_ref() {
            callback();
        }
    }

    /// `scanningStopped`.
    pub fn scanning_stopped(&self) {
        if let Some(callback) = self.scanning_stopped_callback.borrow().as_ref() {
            callback();
        }
    }

    /// `findTaskInfo`: the info record for `task`, if any.
    pub fn find_task_info(&self, task: &ConversionTask) -> Option<TaskInfo> {
        self.all.borrow().get(&task_key(task)).cloned()
    }

    /// `findOrCreateTaskInfo`.
    pub fn find_or_create_task_info(&self, task: &ConversionTask) -> TaskInfo {
        let key = task_key(task);
        let mut all = self.all.borrow_mut();
        all.entry(key)
            .or_insert_with(|| TaskInfo::new(task))
            .clone()
    }

    /// `resetTask`: clear the info record and evict the task from the
    /// completed list (the JIT calls this before re-queueing a task).
    pub fn reset_task(&self, task: &ConversionTask) {
        let key = task_key(task);
        let mut info = self.find_or_create_task_info(task);
        info.log.clear();
        info.outputs.clear();
        info.sub_tasks.clear();
        info.errors = false;
        info.warnings = false;
        self.all.borrow_mut().insert(key, info);
        self.completed.borrow_mut().remove(&key);
    }

    /// `addRequestedTask`: record the task in the requested list (idempotent).
    pub fn add_requested_task(&self, task: &ConversionTask) {
        let key = task_key(task);
        if self.requested.borrow().contains(&key) {
            return;
        }
        self.find_or_create_task_info(task);
        self.requested.borrow_mut().insert(key);
    }

    /// `setTaskCurrent`.
    pub fn set_task_current(&self, task: &ConversionTask) {
        let key = task_key(task);
        self.find_or_create_task_info(task);
        self.current.borrow_mut().insert(key);
    }

    /// `setTaskComplete`: move the task out of the current and requested
    /// lists into the completed list.
    pub fn set_task_complete(&self, task: &ConversionTask) {
        let key = task_key(task);
        assert!(
            self.find_task_info(task).is_some(),
            "setTaskComplete on an unknown task"
        );
        self.current.borrow_mut().remove(&key);
        let removed_from_requested = self.requested.borrow_mut().remove(&key);
        self.completed.borrow_mut().insert(key);
        let _ = removed_from_requested;
    }

    /// `setCurrentTaskState`.
    pub fn set_current_task_state(&self, task: &ConversionTask, state: TaskInfoState) {
        let key = task_key(task);
        if let Some(info) = self.all.borrow_mut().get_mut(&key) {
            info.state = state;
        }
    }

    /// `handleTaskMessage`: append `message` to the task's log and raise its
    /// error/warning flags per the priority. Returns `true` when the task
    /// was known (the store handled the message).
    pub fn handle_task_message(
        &self,
        task: &ConversionTask,
        priority: TaskMessagePriority,
        message: &str,
    ) -> bool {
        let key = task_key(task);
        let mut all = self.all.borrow_mut();
        let Some(info) = all.get_mut(&key) else {
            return false;
        };
        info.log.push(format!("{:?}: {}", priority, message));
        match priority {
            TaskMessagePriority::Error => info.errors = true,
            TaskMessagePriority::Warning => info.warnings = true,
            TaskMessagePriority::Info => {}
        }
        true
    }

    /// `appendLogToTask`.
    pub fn append_log_to_task(&self, task: &ConversionTask, message: &str) {
        let key = task_key(task);
        if let Some(info) = self.all.borrow_mut().get_mut(&key) {
            info.log.push(message.to_string());
        }
    }

    /// `addOutputToTask`.
    pub fn add_output_to_task(&self, task: &ConversionTask, output: &str) {
        let key = task_key(task);
        if let Some(info) = self.all.borrow_mut().get_mut(&key) {
            info.outputs.push(output.to_string());
        }
    }

    /// `addOutputToTask` keyed by the task identity — for callers that only
    /// track the current task by address (the JIT hook's `onOutputGenerated`,
    /// which receives no task argument, just like the reference reads
    /// `st_currentTask_`).
    pub fn add_output_to_task_key(&self, key: TaskKey, output: &str) {
        if let Some(info) = self.all.borrow_mut().get_mut(&key) {
            info.outputs.push(output.to_string());
        }
    }

    /// `updateErrorWarningCounts`: recount failures and warnings over the
    /// info records.
    pub fn update_error_warning_counts(&self) {
        let mut failed = 0;
        let mut warnings = 0;
        for info in self.all.borrow().values() {
            if info.errors {
                failed += 1;
            }
            if info.warnings {
                warnings += 1;
            }
        }
        self.failed_count.set(failed);
        self.warning_count.set(warnings);
    }

    /// `failuresExist`.
    pub fn failures_exist(&self) -> bool {
        self.failed_count.get() > 0
    }

    /// `warningsExist`.
    pub fn warnings_exist(&self) -> bool {
        self.warning_count.get() > 0
    }

    /// `failedCount`.
    pub fn failed_count(&self) -> i32 {
        self.failed_count.get()
    }

    /// `warningCount`.
    pub fn warning_count(&self) -> i32 {
        self.warning_count.get()
    }

    // --- the queryable face (the reference exposes the lists to the UI
    // through its signals; the port hands out membership directly) ---

    /// `requestedTasks_.contains`.
    pub fn is_requested(&self, task: &ConversionTask) -> bool {
        self.requested.borrow().contains(&task_key(task))
    }

    /// `currentTasks_.contains`.
    pub fn is_current(&self, task: &ConversionTask) -> bool {
        self.current.borrow().contains(&task_key(task))
    }

    /// `completedTasks_.contains`.
    pub fn is_completed(&self, task: &ConversionTask) -> bool {
        self.completed.borrow().contains(&task_key(task))
    }
}

/// The message priorities `handleTaskMessage` distinguishes (the reference's
/// `DebugMessagePriority` levels the JIT tool surfaces).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TaskMessagePriority {
    Info,
    Warning,
    Error,
}

/// The shared store handle (the JIT compiler and its hook share one).
pub type SharedTaskStore = Rc<TaskStore>;

#[cfg(test)]
mod tests {
    use super::*;

    /// A fresh task handle for the tests.
    fn make_task(source: &str) -> crate::conversion_task::TaskHandle {
        ConversionTask::new(source).handle()
    }

    /// The lifecycle moves a task requested → current → completed, and
    /// `resetTask` evicts it from the completed list.
    #[test]
    fn task_lifecycle_moves_through_the_lists() {
        let store = TaskStore::new();
        let task = make_task("a.model");
        let borrowed = task.borrow();

        assert!(!store.is_requested(&borrowed));
        store.add_requested_task(&borrowed);
        assert!(store.is_requested(&borrowed));
        // Idempotent: a second add is a no-op (no signal equivalent here,
        // the membership is unchanged).
        store.add_requested_task(&borrowed);
        assert!(store.is_requested(&borrowed));

        store.set_task_current(&borrowed);
        assert!(store.is_current(&borrowed));

        store.set_task_complete(&borrowed);
        assert!(store.is_completed(&borrowed));
        assert!(!store.is_current(&borrowed));
        assert!(!store.is_requested(&borrowed));

        store.reset_task(&borrowed);
        assert!(!store.is_completed(&borrowed));
    }

    /// `handleTaskMessage` appends to the log, raises the flags by priority
    /// and answers `false` for an unknown task.
    #[test]
    fn messages_land_on_the_task_log() {
        let store = TaskStore::new();
        let task = make_task("a.model");
        let borrowed = task.borrow();
        store.find_or_create_task_info(&borrowed);

        assert!(store.handle_task_message(&borrowed, TaskMessagePriority::Warning, "degraded"));
        assert!(store.handle_task_message(&borrowed, TaskMessagePriority::Error, "boom"));
        assert!(store.handle_task_message(&borrowed, TaskMessagePriority::Info, "note"));

        let info = store.find_task_info(&borrowed).unwrap();
        assert_eq!(info.log.len(), 3);
        assert!(info.errors);
        assert!(info.warnings);

        let unknown = make_task("never-seen.model");
        assert!(!store.handle_task_message(&unknown.borrow(), TaskMessagePriority::Error, "x"));

        store.update_error_warning_counts();
        assert!(store.failures_exist());
        assert!(store.warnings_exist());
        assert_eq!(store.failed_count(), 1);
        assert_eq!(store.warning_count(), 1);
    }

    /// Outputs, state changes and the scanning callbacks round-trip.
    #[test]
    fn outputs_states_and_scanning_callbacks() {
        let store = TaskStore::new();
        let started = Rc::new(std::cell::Cell::new(false));
        let stopped = Rc::new(std::cell::Cell::new(false));
        let started_flag = started.clone();
        let stopped_flag = stopped.clone();
        store.set_status_callbacks(
            Some(Box::new(move || started_flag.set(true))),
            Some(Box::new(move || stopped_flag.set(true))),
        );

        store.scanning_started();
        store.scanning_stopped();
        assert!(started.get());
        assert!(stopped.get());

        let task = make_task("b.model");
        let borrowed = task.borrow();
        store.find_or_create_task_info(&borrowed);
        store.set_current_task_state(&borrowed, TaskInfoState::Converting);
        store.add_output_to_task(&borrowed, "out.model");
        store.append_log_to_task(&borrowed, "converted");

        let info = store.find_task_info(&borrowed).unwrap();
        assert_eq!(info.state, TaskInfoState::Converting);
        assert_eq!(info.outputs, vec!["out.model".to_string()]);
        assert_eq!(info.source, "b.model");

        store.reset_task(&borrowed);
        let info = store.find_task_info(&borrowed).unwrap();
        assert!(info.outputs.is_empty());
        assert!(info.log.is_empty());
        // resetTask clears the log/outputs/flags but not the state (the
        // reference's resetTask has no setState call).
        assert_eq!(info.state, TaskInfoState::Converting);
    }
}
