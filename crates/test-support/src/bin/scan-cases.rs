//! Scan the reference checkout for `TEST()` registrations (BW-18-01-04).
//!
//! Usage: `cargo run -p test-support --bin scan-cases <reference-root> [output]`
//!
//! Walks `<root>/lib/**/unit_test*/**/*.cpp`, extracts every top-level
//! `TEST( Name )` registration and writes one tab-separated record per
//! case: `module <TAB> file <TAB> line <TAB> name`, sorted by module, file
//! then line. The output feeds `cases/original_inventory.txt`, the fixed
//! population the case registry traces against.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    let Some(root) = args.next() else {
        eprintln!("usage: scan-cases <reference-root> [output]");
        return ExitCode::from(2);
    };
    let output = args.next();

    let root = PathBuf::from(root);
    let lib = root.join("lib");
    if !lib.is_dir() {
        eprintln!("no lib/ directory under {}", root.display());
        return ExitCode::from(2);
    }

    let mut records = scan(&root);
    records.sort();

    let text = render(&records);
    match output {
        Some(path) => {
            if let Some(parent) = Path::new(&path).parent() {
                std::fs::create_dir_all(parent).expect("output parent directory");
            }
            std::fs::write(&path, text).expect("write inventory");
            println!("{} cases -> {path}", records.len());
        }
        None => print!("{text}"),
    }
    ExitCode::SUCCESS
}

/// One `TEST( Name )` registration.
#[derive(Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Record {
    module: String,
    file: String,
    line: u32,
    name: String,
}

/// Collect records from every `unit_test*` directory under `<root>/lib`.
fn scan(root: &Path) -> Vec<Record> {
    let lib = root.join("lib");
    let mut records = Vec::new();
    let mut worklist = vec![lib.clone()];
    while let Some(dir) = worklist.pop() {
        // Only directories named `unit_test*` hold the case files; build
        // output and scratch data elsewhere are skipped, but their parent
        // module directories must still be descended into.
        let in_unit_test_dir = dir
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| name.starts_with("unit_test"));
        let entries = match std::fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                worklist.push(path);
            } else if in_unit_test_dir
                && path.extension().and_then(|ext| ext.to_str()) == Some("cpp")
            {
                records.extend(scan_file(root, &path));
            }
        }
    }
    records
}

/// Extract the `TEST( Name )` registrations of one source file.
fn scan_file(root: &Path, path: &Path) -> Vec<Record> {
    let Ok(text) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    let module = path
        .strip_prefix(root.join("lib"))
        .ok()
        .and_then(|rest| rest.components().next())
        .and_then(|part| part.as_os_str().to_str())
        .unwrap_or("unknown")
        .to_string();
    let file = path
        .strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .into_owned();

    text.lines()
        .enumerate()
        .filter_map(|(index, line)| {
            let name = case_name(line)?;
            Some(Record {
                module: module.clone(),
                file: file.clone(),
                line: (index + 1) as u32,
                name,
            })
        })
        .collect()
}

/// The case name of a `TEST( Name )` line, or `None` for other lines.
fn case_name(line: &str) -> Option<String> {
    let trimmed = line.trim_start();
    if !trimmed.starts_with("TEST(") {
        return None;
    }
    let inner = trimmed
        .strip_prefix("TEST(")
        .and_then(|rest| rest.rsplit_once(')'))
        .map(|(name, _)| name.trim())?;
    if inner.is_empty() {
        None
    } else {
        Some(inner.to_string())
    }
}

/// Render records with a self-describing header the registry parser skips.
fn render(records: &[Record]) -> String {
    let mut out = String::from(
        "# Reference unit-test inventory, generated by test-support's\n\
         # scan-cases (BW-18-01-04). One tab-separated record per original\n\
         # case: module, file, line, name.\n",
    );
    for record in records {
        out.push_str(&record.module);
        out.push('\t');
        out.push_str(&record.file);
        out.push('\t');
        out.push_str(&record.line.to_string());
        out.push('\t');
        out.push_str(&record.name);
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(path: &Path, text: &str) {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    fn scratch(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "scan_cases_{tag}_{}_{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn case_names_come_from_test_registrations() {
        assert_eq!(
            case_name("TEST( RequestFail_hungPeerTimesOut )"),
            Some("RequestFail_hungPeerTimesOut".to_string())
        );
        assert_eq!(case_name("TEST (no paren)"), None);
        assert_eq!(
            case_name("    TEST( IndentedCase )"),
            Some("IndentedCase".to_string())
        );
        assert_eq!(case_name("TEST( )"), None);
        assert_eq!(case_name("runTest(); // TEST( NotACase )"), None);
    }

    #[test]
    fn scan_walks_only_unit_test_directories() {
        let root = scratch("walk");
        write(
            &root.join("lib/network/unit_test/test_a.cpp"),
            "TEST( FirstCase )\nvoid f() {}\nTEST( SecondCase )\n",
        );
        write(
            &root.join("lib/network/tools/gen.cpp"),
            "TEST( NotACase )\n",
        );
        write(
            &root.join("lib/cstdmf/unit_test/test_b.cpp"),
            "TEST( OtherModule )\n",
        );

        let mut records = scan(&root);
        records.sort();

        // Both registrations of test_a.cpp are found, OtherModule comes
        // from the other module, and `tools/gen.cpp` is not scanned.
        assert_eq!(records.len(), 3);
        assert_eq!(records[0].module, "cstdmf");
        assert_eq!(records[0].name, "OtherModule");
        assert_eq!(records[1].module, "network");
        assert_eq!(records[1].name, "FirstCase");
        assert_eq!(records[1].line, 1);
        assert!(
            records[1]
                .file
                .ends_with("lib/network/unit_test/test_a.cpp")
        );
        assert_eq!(records[2].name, "SecondCase");
        assert_eq!(records[2].line, 3);
        assert!(records.iter().all(|r| !r.file.ends_with("gen.cpp")));
    }

    #[test]
    fn render_emits_sortable_tab_separated_records() {
        let records = vec![Record {
            module: "network".to_string(),
            file: "lib/network/unit_test/test_a.cpp".to_string(),
            line: 7,
            name: "FirstCase".to_string(),
        }];
        let text = render(&records);
        let lines: Vec<&str> = text.lines().collect();
        assert_eq!(lines.len(), 4);
        assert!(lines[0].starts_with('#'));
        assert_eq!(
            lines[3],
            "network\tlib/network/unit_test/test_a.cpp\t7\tFirstCase"
        );
    }
}
