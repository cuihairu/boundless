// harness call, in source order; the C++-side case
// `Math_vectorReferenceAndReadOnly` is excluded and lives in the
// task's deltas note.

/// One original test case: a name plus its ordered steps.
pub(super) struct Case {
    /// The C++ TEST_F name.
    pub name: &'static str,
    /// The case's Python-side steps, in source order.
    pub steps: &'static [Step],
}

/// One step of an original case, mirroring the helper the C++
/// harness uses: `runPython`, `CHECK_FLOAT`, `CHECK_COUNT`,
/// `CHECK_STRING`, `checkTrue`, `checkRaises`, `checkSucceeds`,
/// and `ProviderStore::tick`.
pub(super) enum Step {
    /// `runPython(source)`: the source must run.
    Run(&'static str),
    /// `CHECK_FLOAT(expression, expected, epsilon)`.
    Float(&'static str, f64, f64),
    /// `CHECK_COUNT(expression, expected)`.
    Count(&'static str, i64),
    /// `CHECK_STRING(expression, expected)`.
    Str(&'static str, &'static str),
    /// `checkTrue(expression)`.
    True(&'static str),
    /// `checkRaises(statement, exception_type_name)`.
    Raises(&'static str, &'static str),
    /// `checkSucceeds(statement)`.
    Succeeds(&'static str),
    /// `ProviderStore::tick(d_time)`.
    Tick(f32),
}

