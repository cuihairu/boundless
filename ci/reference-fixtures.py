#!/usr/bin/env python3
"""Derive the reference fixtures for BW-00-04-03: the resource bundle, the
entity definitions and the database seed, each content-addressed so a run is
reproducible and traceable to the reference's version and the generator that
produced it.

Three fixtures, each recorded as it stands:
  * resource — every file under game/res/bigworld, the resource root the server
    loads, with its size and sha256. The reference ships the scripts bundle
    (the server/common Python libraries and their compiled extensions), not a
    game-content tree, so this is the honest resource record.
  * entity — the entity definition sets: the fantasydemo demo's
    res/scripts/entity_defs/*.def plus alias.xml (the primary set the
    reference runs), and the client_integration example's equivalent set (the
    alternative the entitydef lanes also exercise). Each .def is hashed and
    parsed into its Properties/ClientMethods/CellMethods/BaseMethods summary.
  * database — the db.xml seed the server loads at startup: the LogOnMapping
    (logOnName/password/entity type/entity id) and each entity table's rows,
    canonicalised to plain values, plus the file hash.

Every fixture carries reference_root, reference_commit and the generator that
produced it (programming/bigworld/scripts/generate-fantasydemo-assets.py and
its own sha256), so each is traceable to a version and an input.

Usage:
  ci/reference-fixtures.py REFERENCE_ROOT OUT_DIR
  ci/reference-fixtures.py --self-check REFERENCE_ROOT OUT_DIR

Exits 2 when a source the fixtures need is missing. --self-check verifies the
recorded shapes before writing and exits 3 on a hollow one.
"""

import hashlib
import json
import os
import re
import sys
import xml.etree.ElementTree as ET


COMMENT_RE = re.compile(r"<!--.*?-->", re.S)


def parse_xml(path):
    """Parse a BigWorld resource XML, or None when the file is empty.

    The reference's own files carry comments like
    `<!-- Generated by ... -- do not edit. -->` — the double dash inside a
    comment is invalid XML, which BigWorld's lenient reader accepts and
    ElementTree rejects, so comments are stripped before parsing. Structure
    and text are untouched. An empty or unparseable file returns None so the
    caller records the fixture as hollow rather than crashing the record."""
    with open(path, encoding="utf-8", errors="replace") as f:
        src = f.read()
    if not src.strip():
        return None
    try:
        return ET.fromstring(COMMENT_RE.sub("", src))
    except ET.ParseError:
        return None

RESOURCE_ROOT = os.path.join("game", "res", "bigworld")
ENTITY_SETS = [
    ("fantasydemo", os.path.join("programming", "fantasydemo", "res", "scripts")),
    ("client_integration", os.path.join(
        "programming", "bigworld", "examples", "client_integration",
        "python", "simple", "res", "scripts")),
]
GENERATOR = os.path.join("programming", "bigworld", "scripts",
                         "generate-fantasydemo-assets.py")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def content_manifest(root, rel):
    """[(path, size, sha256)] for every file under root/rel, sorted by path."""
    base = os.path.join(root, rel)
    out = []
    for dirpath, _dirs, files in os.walk(base):
        for name in sorted(files):
            full = os.path.join(dirpath, name)
            relpath = os.path.relpath(full, root)
            out.append({
                "path": relpath,
                "size": os.path.getsize(full),
                "sha256": sha256_file(full),
            })
    return out


def text_of(el):
    """The text of an element, trimmed — the plain value a fixture wants."""
    return (el.text or "").strip()


def children_text(el):
    """{tag: text} for an element's direct children (first occurrence wins)."""
    out = {}
    for c in el:
        if c.tag in out:
            continue
        out[c.tag] = text_of(c)
    return out


def parse_entity_def(path):
    """The entity summary: properties, the client/cell/base method names, and
    the Identifier, if the def declares one."""
    root = parse_xml(path)
    if root is None:
        return None
    props, ident = {}, None
    methods = {"client": [], "cell": [], "base": []}
    for sec in root:
        tag = sec.tag
        if tag == "Properties":
            for p in sec:
                if p.tag == "Identifier":
                    ident = text_of(p)
                elif p.tag not in ("_BigWorldInfo",):
                    props[p.tag] = children_text(p)
        elif tag == "ClientMethods":
            methods["client"] = sorted(m.tag for m in sec)
        elif tag == "CellMethods":
            methods["cell"] = sorted(m.tag for m in sec)
        elif tag == "BaseMethods":
            methods["base"] = sorted(m.tag for m in sec)
    return {
        "properties": props,
        "client_methods": methods["client"],
        "cell_methods": methods["cell"],
        "base_methods": methods["base"],
        "identifier": ident,
    }


def entity_fixture(root):
    """The entity definition sets: files hashed, defs parsed, alias hashed."""
    sets = []
    for name, scripts_rel in ENTITY_SETS:
        defs_rel = os.path.join(scripts_rel, "entity_defs")
        if not os.path.isdir(os.path.join(root, defs_rel)):
            continue
        files = []
        entities = {}
        for f in sorted(os.listdir(os.path.join(root, defs_rel))):
            full = os.path.join(root, defs_rel, f)
            relpath = os.path.join(defs_rel, f)
            entry = {
                "path": relpath,
                "size": os.path.getsize(full),
                "sha256": sha256_file(full),
            }
            files.append(entry)
            if f.endswith(".def"):
                summary = parse_entity_def(full)
                if summary is not None:
                    entities[f[:-4]] = summary
        sets.append({
            "set": name,
            "files": files,
            "entities": entities,
        })
    return sets


def database_fixture(root):
    """The db.xml seed: LogOnMapping plus each entity table's rows."""
    out = []
    for name, scripts_rel in ENTITY_SETS:
        db_path = os.path.join(root, scripts_rel, "db.xml")
        if not os.path.isfile(db_path):
            continue
        doc = parse_xml(db_path)
        if doc is None:
            continue
        logon = []
        tables = {}
        for child in doc:
            tag = child.tag
            if tag == "_BigWorldInfo":
                mapping = child.find("LogOnMapping")
                if mapping is not None:
                    for item in mapping:
                        logon.append(children_text(item))
            elif tag in ("Account", "Avatar", "Space", "Guard", "ClientOnly"):
                tables[tag] = children_text(child)
        out.append({
            "set": name,
            "path": os.path.relpath(db_path, root),
            "sha256": sha256_file(db_path),
            "logon_mapping": logon,
            "tables": tables,
        })
    return out


def emit(root, out_dir, self_check=False):
    missing = []
    if not os.path.isdir(os.path.join(root, RESOURCE_ROOT)):
        missing.append(RESOURCE_ROOT)
    if not os.path.isfile(os.path.join(root, GENERATOR)):
        missing.append(GENERATOR)
    if not os.path.isfile(os.path.join(root, ENTITY_SETS[0][1], "db.xml")):
        missing.append(os.path.join(ENTITY_SETS[0][1], "db.xml"))
    if missing:
        sys.stderr.write("missing source(s): %s\n" % ", ".join(missing))
        sys.exit(2)

    commit = "unknown"
    try:
        commit = os.popen("git -C %s rev-parse HEAD 2>/dev/null" % root).read().strip() \
            or "unknown"
    except OSError:
        pass
    gen_path = os.path.join(root, GENERATOR)
    anchor = {
        "reference_root": os.path.abspath(root),
        "reference_commit": commit,
        "generator": GENERATOR,
        "generator_sha256": sha256_file(gen_path),
    }

    resource = content_manifest(root, RESOURCE_ROOT)
    entities = entity_fixture(root)
    dbs = database_fixture(root)

    if self_check:
        problems = []
        if not resource:
            problems.append("resource manifest is empty")
        if not entities:
            problems.append("no entity definition set")
        elif not entities[0]["entities"]:
            problems.append("the primary entity set parsed no defs")
        if not dbs:
            problems.append("no database fixture")
        elif not dbs[0]["logon_mapping"] and not dbs[0]["tables"]:
            problems.append("the primary db.xml parsed no rows")
        if problems:
            sys.stderr.write("hollow fixture: %s\n" % "; ".join(problems))
            sys.exit(3)

    os.makedirs(out_dir, exist_ok=True)
    fixtures = {
        "resource": {"face": "reference resource bundle", **anchor,
                     "file_count": len(resource), "total_bytes": sum(
                         f["size"] for f in resource),
                     "files": resource},
        "entity": {"face": "reference entity definitions", **anchor,
                   "sets": entities},
        "database": {"face": "reference database seed", **anchor,
                     "sets": dbs},
    }
    for name, data in fixtures.items():
        with open(os.path.join(out_dir, "fixture-%s.json" % name), "w") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
    # A compact manifest for the CI record: path, size, sha256 per resource
    # file, plus the anchor line.
    with open(os.path.join(out_dir, "fixture-resource.tsv"), "w") as f:
        f.write("# reference_commit=%s generator=%s generator_sha256=%s\n" % (
            commit, GENERATOR, anchor["generator_sha256"]))
        f.write("path\tsize\tsha256\n")
        for e in resource:
            f.write("%s\t%d\t%s\n" % (e["path"], e["size"], e["sha256"]))
    return {
        "resource_files": len(resource),
        "resource_bytes": sum(f["size"] for f in resource),
        "entity_sets": len(entities),
        "entity_defs": sum(len(s["entities"]) for s in entities),
        "db_sets": len(dbs),
    }


if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.environ.get("HOME", ""), "workspaces", "BigWorld")
    out_dir = sys.argv[2] if len(sys.argv) > 2 else "."
    self_check = len(sys.argv) > 3 and sys.argv[3] == "--self-check"
    summary = emit(root, out_dir, self_check)
    print("resource=%d files/%d bytes entity_sets=%d entity_defs=%d db_sets=%d" % (
        summary["resource_files"], summary["resource_bytes"],
        summary["entity_sets"], summary["entity_defs"], summary["db_sets"]))
