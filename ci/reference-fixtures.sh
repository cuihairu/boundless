#!/usr/bin/env bash
# BW-00-04-03 — the reference fixtures: the resource bundle, the entity
# definitions and the database seed, each content-addressed so a run is
# reproducible and every fixture is traceable to the reference's version and
# the generator that produced it. Recorded from the original's own tree
# without inventing a byte of it.
#
# Usage:
#   ci/reference-fixtures.sh            # record the three fixtures
#   ci/reference-fixtures.sh self-test  # planted fixtures, planted gaps
#
# Three fixture faces, each recorded as it stands:
#   * resource — every file under game/res/bigworld (the resource root the
#     server loads) with its size and sha256, plus a TSV manifest. The
#     reference ships the scripts bundle (server/common Python libraries and
#     their compiled extensions), not a game-content tree, so this is the
#     honest resource record.
#   * entity — the entity definition sets: the fantasydemo demo's
#     res/scripts/entity_defs/*.def plus alias.xml (primary) and the
#     client_integration example's equivalent set (alternative). Each .def is
#     hashed and parsed into its Properties/ClientMethods/CellMethods/
#     BaseMethods summary.
#   * database — the db.xml seed the server loads: the LogOnMapping
#     (logOnName/password/entity type/entity id) and each entity table's
#     rows, canonicalised to plain values, plus the file hash.
#
# Every fixture carries reference_root, reference_commit and the generator
# that produced it (programming/bigworld/scripts/generate-fantasydemo-assets.
# py, hashed), so each is traceable to a version and an input. There is no
# live capture here: these are static files in the tree, so the gate is
# presence — a missing source fails, an absent tree skips.

set -uo pipefail
# shellcheck source=ci/lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

MODE="${1:-all}"
cur_ref() { printf '%s' "${CI_FIXTURES_ROOT:-${BW_REFERENCE:-$HOME/workspaces/BigWorld}}"; }
cur_out() { printf '%s' "${CI_FIXTURES_OUT:-$CI_OUT}"; }

fixture_out() { printf '%s/reference-fixtures' "$(cur_out)"; }
committed_resource() { printf '%s/tests/baseline/fixture-resource.json' "$REPO_ROOT"; }
committed_entity() { printf '%s/tests/baseline/fixture-entity.json' "$REPO_ROOT"; }
committed_database() { printf '%s/tests/baseline/fixture-database.json' "$REPO_ROOT"; }

# The sources each fixture face needs. A fixture with a missing source is
# hollow: a resource record with no resource root, an entity record with no
# definition set and a database record with no seed are not records.
FIXTURE_SOURCES=(
    game/res/bigworld
    programming/bigworld/scripts/generate-fantasydemo-assets.py
    programming/fantasydemo/res/scripts/entity_defs
    programming/fantasydemo/res/scripts/db.xml
)

# The fixture the self-test plants: the resource file, the alias, the two
# entity defs and the db.xml seed. The defs carry the same `-- do not edit.`
# comment inside `<!-- ... -->` the reference ships, so the parse path is
# exercised the way it runs against the real tree.
plant_tree() { # $1 root  $2 "with fixtures" | "empty"
    local root="$1" kind="$2"
    mkdir -p "$root/game/res/bigworld/scripts/server_common" \
        "$root/game/res/bigworld/scripts/common" \
        "$root/programming/bigworld/scripts" \
        "$root/programming/fantasydemo/res/scripts/entity_defs"

    printf 'BW_RES_PATH=bigworld\n' >"$root/game/res/bigworld/scripts/server_common/__init__.py"
    printf '# common module\n' >"$root/game/res/bigworld/scripts/common/__init__.py"
    printf '#!/usr/bin/env python3\ndef generate():\n    pass\n' \
        >"$root/programming/bigworld/scripts/generate-fantasydemo-assets.py"

    if [ "$kind" = "with fixtures" ]; then
        cat >"$root/programming/fantasydemo/res/scripts/entity_defs/Account.def" <<'DEF'
<root>
<!-- Generated by scripts/generate-fantasydemo-assets.py -- do not edit. -->
	<Properties>
		<playerName>
			<Type>	STRING	</Type>
			<Flags>	BASE_AND_CLIENT	</Flags>
			<Persistent>	true	</Persistent>
			<Editable>	true	</Editable>
		</playerName>
	</Properties>
	<ClientMethods>
		<chatMessage>
			<Arg>	STRING	</Arg>
		</chatMessage>
	</ClientMethods>
	<CellMethods>
	</CellMethods>
	<BaseMethods>
	</BaseMethods>
</root>
DEF
        cat >"$root/programming/fantasydemo/res/scripts/entity_defs/Avatar.def" <<'DEF'
<root>
<!-- Generated by scripts/generate-fantasydemo-assets.py -- do not edit. -->
	<Properties>
		<playerName>
			<Type>	STRING	</Type>
		</playerName>
	</Properties>
	<ClientMethods>
	</ClientMethods>
	<CellMethods>
		<cellTick>
			<Arg>	FLOAT	</Arg>
		</cellTick>
	</CellMethods>
	<BaseMethods>
	</BaseMethods>
</root>
DEF
        cat >"$root/programming/fantasydemo/res/scripts/entity_defs/alias.xml" <<'ALIAS'
<root>
<!-- Generated by scripts/generate-fantasydemo-assets.py -- do not edit. -->
	<OBJECT_ID>	INT32	</OBJECT_ID>
</root>
ALIAS
        cat >"$root/programming/fantasydemo/res/scripts/db.xml" <<'DB'
<db.xml>
<!-- Generated by scripts/generate-fantasydemo-assets.py -- do not edit. -->
	<_BigWorldInfo>
		<LogOnMapping>
			<item>
				<logOnName>	FantasyAccount	</logOnName>
				<password>	a	</password>
				<type>	Account	</type>
				<entityID>	2	</entityID>
			</item>
		</LogOnMapping>
	</_BigWorldInfo>
	<Account>
		<playerName>	FantasyAccount	</playerName>
		<databaseID>	2	</databaseID>
	</Account>
</db.xml>
DB
    else
        : >"$root/programming/fantasydemo/res/scripts/entity_defs/alias.xml"
        : >"$root/programming/fantasydemo/res/scripts/db.xml"
    fi
}

# Run the recorder, demand a non-hollow result on every face, print the
# summary a caller can verify.
record_fixtures() { # prints "resource|entity|database|commit"
    local ref head
    ref="$(cur_ref)"
    head="$(git -C "$ref" rev-parse HEAD 2>/dev/null || echo unknown)"
    [ "$(git -C "$ref" rev-parse --show-toplevel 2>/dev/null || echo "")" = "$ref" ] \
        || head="unknown (not the reference's own git toplevel)"

    local out dir
    dir="$(fixture_out)"
    mkdir -p "$dir"
    if ! out="$(python3 "$REPO_ROOT/ci/reference-fixtures.py" "$ref" "$dir" --self-check 2>&1)"; then
        printf '%s' "$out"
        return 1
    fi
    printf '%s|%s|%s\n' "$(printf '%s' "$out" | sed -n 's/.*resource=\([0-9]*\) files.*/\1/p')" \
        "$(printf '%s' "$out" | sed -n 's/.*entity_defs=\([0-9]*\).*/\1/p')" \
        "$(printf '%s' "$out" | sed -n 's/.*db_sets=\([0-9]*\).*/\1/p')|$head"
}

run_all() {
    mkdir -p "$CI_OUT" "$CI_LOG_DIR"
    [ -n "${GITHUB_ENV:-}" ] && ci_out_env >>"$GITHUB_ENV"

    ci_step "reference fixtures"
    if [ ! -d "$(cur_ref)" ]; then
        ci_skip reference-fixtures \
            "no reference tree at $(cur_ref) — BW-00-04-03 records it when present (set BW_REFERENCE)"
        return 0
    fi

    # Every fixture source must be present, else the record would be partial —
    # a resource set with no resource root or an entity set with no defs is
    # a hollow baseline, not a fixture.
    local missing="" f
    for f in "${FIXTURE_SOURCES[@]}"; do
        [ -e "$(cur_ref)/$f" ] || missing="$missing $f"
    done
    if [ -n "$missing" ]; then
        ci_fail fixture-record \
            "fixture source missing:$missing — a record with a partial source set is hollow"
        return 1
    fi

    local sum res ent db head
    if ! sum="$(record_fixtures)"; then
        ci_fail fixture-record "the recorder failed to record the fixtures: $(printf '%s' "$sum" | tail -1)"
        return 1
    fi
    res="$(printf '%s' "$sum" | cut -d'|' -f1)"
    ent="$(printf '%s' "$sum" | cut -d'|' -f2)"
    db="$(printf '%s' "$sum" | cut -d'|' -f3)"
    head="$(printf '%s' "$sum" | cut -d'|' -f4)"
    if [ -z "$res" ] || [ "$res" -lt 1 ] || [ -z "$ent" ] || [ "$ent" -lt 1 ] \
        || [ -z "$db" ] || [ "$db" -lt 1 ]; then
        ci_fail fixture-record \
            "recorded $res resource file(s), $ent entity def(s), $db db set(s) — a hollow baseline is not a fixture"
        return 1
    fi
    ci_pass fixture-record \
        "resource $res file(s), entity $ent def(s), database $db set(s) recorded (commit $head)"

    # The committed baselines are the snapshot-time anchor; a live run that
    # differs is recorded as a note, not a failure.
    local j
    for j in resource entity database; do
        case "$j" in
        resource) committed="$(committed_resource)" ;;
        entity) committed="$(committed_entity)" ;;
        database) committed="$(committed_database)" ;;
        esac
        if [ -f "$committed" ] && ! cmp -s "$committed" "$(fixture_out)/fixture-$j.json"; then
            ci_note "the committed tests/baseline/fixture-$j.json differs from this run — snapshot-time anchor, not a failure"
        fi
    done

    ci_note "fixtures recorded; capture: static files (no live capture — the gate is source presence)"
}

self_test() {
    local fails=0 rc r T M r2 T2 M2
    ci_step "self-test: a planted fixture tree records resource, entity and database"
    r="$(mktemp -d "$REPO_ROOT/ci-out/fixtures-selftest.XXXXXX")"
    T="$r/BigWorld"
    M="$r/manifest/manifest.tsv"
    plant_tree "$T" "with fixtures"

    CI_FIXTURES_ROOT="$T" CI_FIXTURES_OUT="$r/out" CI_OUT="$r/manifest" "$0" >/dev/null 2>&1
    rc=$?
    if [ "$rc" -eq 0 ] \
        && grep -q 'fixture-record	PASS	resource 2 file(s), entity 2 def(s), database 1 set(s)' "$M" \
        && grep -q '"sha256"' "$r/out/reference-fixtures/fixture-resource.json" \
        && grep -q '"chatMessage"' "$r/out/reference-fixtures/fixture-entity.json" \
        && grep -q '"logOnName": "FantasyAccount"' "$r/out/reference-fixtures/fixture-database.json" \
        && grep -q 'generator_sha256' "$r/out/reference-fixtures/fixture-resource.json"; then
        ci_pass selftest-fixtures "planted sources record the resource, entity and database fixtures with their hashes"
    else
        ci_fail selftest-fixtures "planted sources did not record: rc=$rc $(grep -E 'fixture-' "$M" 2>/dev/null | head -1 | tr '\n' '; ')"
        fails=$((fails + 1))
    fi

    ci_step "self-test: an empty definition set and a seedless db.xml are hollow"
    r2="$(mktemp -d "$REPO_ROOT/ci-out/fixtures-selftest.XXXXXX")"
    T2="$r2/BigWorld"
    M2="$r2/manifest/manifest.tsv"
    plant_tree "$T2" "empty"
    CI_FIXTURES_ROOT="$T2" CI_FIXTURES_OUT="$r2/out" CI_OUT="$r2/manifest" "$0" >/dev/null 2>&1
    rc=$?
    if [ "$rc" -ne 0 ] \
        && grep -q 'fixture-record	FAIL	.*hollow' "$M2"; then
        ci_pass selftest-fixtures-hollow "an empty definition set fails the record leg"
    else
        ci_fail selftest-fixtures-hollow "a hollow record did not fail loudly: rc=$rc $(grep 'fixture-record' "$M2" 2>/dev/null | head -1)"
        fails=$((fails + 1))
    fi

    ci_step "self-test: a resource-less tree fails by the missing source it names"
    r2="$(mktemp -d "$REPO_ROOT/ci-out/fixtures-selftest.XXXXXX")"
    T2="$r2/BigWorld"
    M2="$r2/manifest/manifest.tsv"
    plant_tree "$T2" "with fixtures"
    rm -rf "$T2/game"
    CI_FIXTURES_ROOT="$T2" CI_FIXTURES_OUT="$r2/out" CI_OUT="$r2/manifest" "$0" >/dev/null 2>&1
    rc=$?
    if [ "$rc" -ne 0 ] \
        && grep -q 'fixture-record	FAIL	.*game/res/bigworld' "$M2"; then
        ci_pass selftest-fixtures-missing "a tree with no resource root fails naming it"
    else
        ci_fail selftest-fixtures-missing "a missing resource root did not fail naming it: rc=$rc $(grep 'fixture-record' "$M2" 2>/dev/null | head -1)"
        fails=$((fails + 1))
    fi

    ci_step "self-test: no reference tree reports SKIP naming the ticket"
    r2="$(mktemp -d "$REPO_ROOT/ci-out/fixtures-selftest.XXXXXX")"
    T2="$r2/none"
    M2="$r2/manifest/manifest.tsv"
    CI_FIXTURES_ROOT="$T2" CI_FIXTURES_OUT="$r2/out" CI_OUT="$r2/manifest" "$0" >/dev/null 2>&1
    rc=$?
    if [ "$rc" -eq 0 ] && grep -q 'reference-fixtures	SKIP	.*BW-00-04-03' "$M2"; then
        ci_pass selftest-fixtures-absent "absent tree reports SKIP naming BW-00-04-03"
    else
        ci_fail selftest-fixtures-absent "absent tree did not skip cleanly: rc=$rc"
        fails=$((fails + 1))
    fi

    rm -rf "$r" "$r2" "$REPO_ROOT/ci-out/fixtures-selftest".*

    if [ "$fails" -gt 0 ]; then
        ci_note "$fails self-test(s) did not behave"
        return 1
    fi
    ci_note "all self-tests behaved as expected"
    return 0
}

main() {
    case "$MODE" in
    self-test) self_test; return $? ;;
    esac
    run_all
}

main "$@"
LANE_RC=$?

set +e
ci_finalize
FINAL_RC=$?
set -e

[ "$LANE_RC" -ne 0 ] && exit "$LANE_RC"
exit "$FINAL_RC"
